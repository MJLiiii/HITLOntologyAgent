"""Export actual FastAPI OpenAPI and deterministic request-only TypeScript contracts.

The narrow JSON-schema converter supports the Pydantic request schemas used here.
Response view models remain hand-owned because the API returns generic dictionaries.
"""
import argparse
import json
import os
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def type_expression(schema):
    if '$ref' in schema:
        prefix = '#/components/schemas/'
        reference = schema['$ref']
        if not reference.startswith(prefix) or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', reference[len(prefix):]):
            raise ValueError(f'Unsupported schema reference {reference!r}')
        return reference[len(prefix):]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum']) or 'never'
    for keyword, separator in (('anyOf', ' | '), ('oneOf', ' | '), ('allOf', ' & ')):
        if keyword in schema:
            return '(' + separator.join(type_expression(value) for value in schema[keyword]) + ')'
    kind = schema.get('type')
    if isinstance(kind, list):
        return '(' + ' | '.join(type_expression({**schema, 'type': value}) for value in kind) + ')'
    if kind == 'null':
        return 'null'
    if kind == 'boolean':
        return 'boolean'
    if kind in ('number', 'integer'):
        return 'number'
    if kind == 'string':
        return 'Blob' if schema.get('format') == 'binary' else 'string'
    if kind == 'array':
        return 'Array<' + type_expression(schema.get('items', {})) + '>'
    if kind == 'object' or 'properties' in schema:
        fields = []
        for name, value in sorted(schema.get('properties', {}).items()):
            optional = '' if name in schema.get('required', []) else '?'
            fields.append(f'{json.dumps(name)}{optional}: {type_expression(value)};')
        additional = schema.get('additionalProperties')
        if additional is True or isinstance(additional, dict):
            fields.append('[key: string]: ' + type_expression(additional if isinstance(additional, dict) else {}) + ';')
        return '{ ' + ' '.join(fields) + ' }' if fields else 'Record<string, unknown>'
    if kind is not None:
        raise ValueError(f'Unsupported JSON schema type {kind!r}')
    return 'unknown'


def request_types(schema):
    requests = {}
    roots = []
    for path, methods in sorted(schema['paths'].items()):
        for method, operation in sorted(methods.items()):
            content = operation.get('requestBody', {}).get('content', {})
            for media_type, body in sorted(content.items()):
                key = f'{method.upper()} {path} [{media_type}]'
                requests[key] = type_expression(body['schema'])
                roots.append(body['schema'])
    definitions = schema.get('components', {}).get('schemas', {})
    required = set()

    def collect(value):
        if isinstance(value, dict):
            if '$ref' in value:
                name = type_expression(value)
                if name not in definitions:
                    raise ValueError(f'Missing definition {name}')
                if name not in required:
                    required.add(name)
                    collect(definitions[name])
            for nested in value.values():
                collect(nested)
        elif isinstance(value, list):
            for nested in value:
                collect(nested)

    collect(roots)
    lines = ['/** Generated by scripts/export_openapi.py from the actual FastAPI OpenAPI schema.',
             ' * Request shapes only. Runtime validation constraints remain enforced by FastAPI.',
             ' * Response view models in generated.ts are hand-owned. Do not edit this file. */', '']
    for name in sorted(required):
        lines.append(f'export type {name} = {type_expression(definitions[name])};')
    lines.extend(['', 'export interface ApiRequestBodies {'])
    lines.extend(f'  {json.dumps(name)}: {value};' for name, value in requests.items())
    lines.extend(['}', ''])
    return '\n'.join(lines)


def application_schema():
    # Importing main constructs its app. Keep its seed/key/database strictly temporary.
    with tempfile.TemporaryDirectory(prefix='oe-openapi-') as folder:
        overrides = {'OE_DATA_DIR': folder, 'OE_DATABASE_URL': '', 'OE_EAGER_JOBS': 'true',
                     'OE_MODE': 'local', 'OE_SERVICE_TOKEN': '', 'OE_MODEL_URL': '',
                     'OE_MODEL_API_KEY': '', 'OE_MODEL_NAME': ''}
        previous = {key: os.environ.get(key) for key in overrides}
        os.environ.update(overrides)
        try:
            from oe_studio.main import app
            return app.openapi()
        finally:
            for key, value in previous.items():
                if value is None:
                    os.environ.pop(key, None)
                else:
                    os.environ[key] = value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if checked-in artifacts differ; do not rewrite')
    args = parser.parse_args()
    schema = application_schema()
    outputs = {ROOT / 'docs/openapi.json': json.dumps(schema, indent=2, sort_keys=True) + '\n',
               ROOT / 'apps/studio-plugin/src/api/openapi.ts': request_types(schema)}
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f'Generated contract is stale: {path.relative_to(ROOT)}; run make api-contracts')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('OpenAPI schema and request TypeScript contracts ' + ('verified.' if args.check else 'exported.'))


if __name__ == '__main__':
    main()
